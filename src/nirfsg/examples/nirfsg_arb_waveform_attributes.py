'''Assigns attributes such as the I/Q rate, signal bandwidth, and runtime scaling to individual waveforms.

Based on the "Assigning Properties to a Waveform in NI-RFSG" topic of the NI-RFSG user manual.

Background:
    Each waveform stored on the device can carry its own attributes, set and read through the
    waveforms[] repeated capability, for example session.waveforms['wfmA'].waveform_iq_rate.
    When a waveform is selected (ARB mode) or generated by a script, its attributes are used
    instead of the session-wide values. This lets waveforms that were created at different
    sample rates, or that need different levels, share one session without reconfiguring it
    between generations. The waveform attributes are:
      waveform_iq_rate           - the I/Q rate of the waveform
      waveform_signal_bandwidth  - the bandwidth of the waveform, at most 0.8 * its I/Q rate
      waveform_runtime_scaling   - a gain, in dB, applied to the waveform data when it is
                                   generated, before any other signal processing
      waveform_papr              - the peak-to-average power ratio of the waveform
      waveform_waveform_size     - the number of samples in the waveform
      waveform_rf_blanking       - RF blanking (refer to nirfsg_arb_rf_blanking.py)
    Write the waveform first, then set its attributes; clearing a waveform also clears its
    attributes.

    In SCRIPT mode, NI-RFSG requires the waveforms that one script generates to have the same
    I/Q rate.

    This example writes two versions of a tone, one at 10 MS/s and one at 2 MS/s, gives each its
    own I/Q rate, bandwidth, and runtime scaling, and generates them in turn. Both versions
    produce a tone at the same frequency offset, because each is played at its own I/Q rate.

Steps:
    1. Configure the RF settings and ARB mode.
    2. Write the two waveforms and set the attributes of each.
    3. Print the attributes, then select and generate each waveform.
'''

import argparse
import nirfsg
import numpy as np
import sys
import time


def _tone(tone_offset, iq_rate, number_of_samples):
    cycles = round(tone_offset * number_of_samples / iq_rate)
    return np.exp(2j * np.pi * cycles * np.arange(number_of_samples) / number_of_samples).astype(np.complex64)


def example(resource_name, options, frequency, power_level, tone_offset, generation_time):
    # Two versions of the same tone, sampled at different I/Q rates, with different levels.
    waveforms = {
        'toneFast': {'iq_rate': 10e6, 'runtime_scaling': 0.0},
        'toneSlow': {'iq_rate': 2e6, 'runtime_scaling': -6.0},
    }
    with nirfsg.Session(resource_name=resource_name, id_query=False, reset_device=False, options=options) as session:
        session.configure_rf(frequency, power_level)
        session.generation_mode = nirfsg.GenerationMode.ARB_WAVEFORM

        for name, settings in waveforms.items():
            iq_rate = settings['iq_rate']
            session.write_arb_waveform(name, _tone(tone_offset, iq_rate, int(iq_rate / 1000)), False)

            # The attributes belong to this waveform only.
            waveform = session.waveforms[name]
            waveform.waveform_iq_rate = iq_rate
            waveform.waveform_signal_bandwidth = 2 * abs(tone_offset)
            waveform.waveform_runtime_scaling = settings['runtime_scaling']

        for name in waveforms:
            waveform = session.waveforms[name]
            print(f'{name}: I/Q rate {waveform.waveform_iq_rate / 1e6} MS/s, signal bandwidth {waveform.waveform_signal_bandwidth / 1e6} MHz, '
                  f'runtime scaling {waveform.waveform_runtime_scaling:+.1f} dB, PAPR {waveform.waveform_papr:.2f} dB, {waveform.waveform_waveform_size} samples')

        for name in waveforms:
            # Selecting the waveform also selects its attributes for the next generation.
            session.select_arb_waveform(name)
            print(f'Generating "{name}" for {generation_time} s...')
            with session.initiate():
                end_time = time.monotonic() + generation_time
                while time.monotonic() < end_time:
                    session.check_generation_status()
                    time.sleep(0.1)


def _main(argsv):
    parser = argparse.ArgumentParser(description='Assigns the I/Q rate, signal bandwidth, and runtime scaling to individual NI-RFSG waveforms.', formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    parser.add_argument('-n', '--resource-name', default='PXI1Slot2', help='Resource name of the NI RF signal generator.')
    parser.add_argument('-f', '--frequency', default=1e9, type=float, help='Carrier frequency in Hz.')
    parser.add_argument('-p', '--power-level', default=-10.0, type=float, help='Average power level in dBm.')
    parser.add_argument('-o', '--tone-offset', default=500e3, type=float, help='Frequency offset, in Hz, of the tone from the carrier. Must be below 0.4 * 2 MS/s.')
    parser.add_argument('-t', '--generation-time', default=5.0, type=float, help='Time, in seconds, to generate each waveform.')
    parser.add_argument('-op', '--option-string', default='', type=str, help='Option string for the session.')
    args = parser.parse_args(argsv)
    example(args.resource_name, args.option_string, args.frequency, args.power_level, args.tone_offset, args.generation_time)


def main():
    _main(sys.argv[1:])


def test_example():
    options = {'simulate': True, 'driver_setup': {'Model': '5841', }, }
    example('simulated5841', options, 1e9, -10.0, 500e3, 0.05)


def test_main():
    cmd_line = ['--resource-name', 'simulated5841', '--generation-time', '0.05', '--option-string', 'Simulate=1, DriverSetup=Model:5841']
    _main(cmd_line)


if __name__ == '__main__':
    main()
