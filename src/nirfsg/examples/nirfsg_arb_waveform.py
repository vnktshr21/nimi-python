'''Continuously generates an arbitrary waveform.

Python counterpart of the NI-RFSG .NET "ArbitraryWaveforms/ArbitraryWaveformGeneration" example.

Background:
    In arbitrary waveform (ARB) generation mode, the device plays complex baseband I/Q samples
    stored in its onboard memory, upconverted to the carrier frequency. Each sample I + jQ
    sets the amplitude and the phase of the carrier at that instant, so any modulated signal can
    be generated by writing the right samples:
      - A constant sample value (as in this example, 1 + 0j) is an unmodulated carrier at the
        configured frequency.
      - A rotating phasor exp(j*2*pi*f*t) is a tone offset by f from the carrier.
      - Modulated data, such as filtered QPSK symbols, produces a modulated signal.

    write_arb_waveform() writes a named waveform to the device. It accepts numpy arrays of
    complex128, complex64, or interleaved int16 data. By default the selected waveform repeats
    continuously until the generation is aborted. The rate at which samples are played is the
    I/Q rate (the iq_rate property).

    With the default power_level_type (AVERAGE), power_level is the average power of the
    waveform, and the driver scales the samples accordingly.

Steps:
    1. Open a session, configure the frequency and power level, and select ARB mode.
    2. Write a waveform of constant samples.
    3. Start the generation and check its status.
'''

import argparse
import nirfsg
import numpy as np
import sys


def example(resource_name, options, frequency, power_level, number_of_samples):
    # A constant I/Q value of 1 + 0j produces an unmodulated carrier at the configured frequency.
    waveform_data = np.full(number_of_samples, 1 + 0j, dtype=np.complex128)
    with nirfsg.Session(resource_name=resource_name, id_query=False, reset_device=False, options=options) as session:
        # Carrier frequency in Hz and average power level in dBm.
        session.configure_rf(
            frequency,
            power_level
        )
        session.generation_mode = nirfsg.GenerationMode.ARB_WAVEFORM
        # Write the samples to device memory under the name 'wfm'. more_data_pending=False
        # means that this call writes the complete waveform.
        session.write_arb_waveform('wfm', waveform_data, False)
        # The waveform repeats until the generation is aborted when the "with" block exits.
        with session.initiate():
            session.check_generation_status()


def _main(argsv):
    parser = argparse.ArgumentParser(description='Continuously generates an arbitrary waveform using NI-RFSG.', formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    parser.add_argument('-n', '--resource-name', default='PXI1Slot2', help='Resource name of the NI RF signal generator.')
    parser.add_argument('-f', '--frequency', default=1e9, type=float, help='Frequency in Hz.')
    parser.add_argument('-p', '--power-level', default=-10.0, type=float, help='Power level in dBm.')
    parser.add_argument('-s', '--number-of-samples', default=1000, type=int, help='Number of samples.')
    parser.add_argument('-op', '--option-string', default='', type=str, help='Option string for the session.')
    args = parser.parse_args(argsv)
    example(args.resource_name, args.option_string, args.frequency, args.power_level, args.number_of_samples)


def main():
    _main(sys.argv[1:])


def test_example():
    options = {'simulate': True, 'driver_setup': {'Model': '5841', }, }
    example('simulated5841', options, 1e9, -10.0, 1000)


